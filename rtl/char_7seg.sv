module char_7seg #(
    parameter DATA_WIDTH = 8
) (
    input  logic i_clk,
    input  logic i_rst_n,
    input  logic                  i_valid,
    output logic                  o_ready,
    input  logic [DATA_WIDTH-1:0] i_char,
    output logic [6:0] o_seg
);

    assign o_ready = i_valid;

    logic [DATA_WIDTH-1:0] char_captured;

    `DFF(char_captured, i_char, i_valid)

    // Active-low gfedcba patterns for ASCII '0'..'z' (WikiChip table, inverted)
    localparam logic [6:0] SEG_LUT [75] = '{
        7'b1000000, // '0'
        7'b1111001, // '1'
        7'b0100100, // '2'
        7'b0110000, // '3'
        7'b0011001, // '4'
        7'b0010010, // '5'
        7'b0000010, // '6'
        7'b1111000, // '7'
        7'b0000000, // '8'
        7'b0010000, // '9'
        7'b1111111, // ':'
        7'b1111111, // ';'
        7'b1111111, // '<'
        7'b1111111, // '='
        7'b1111111, // '>'
        7'b1111111, // '?'
        7'b1111111, // '@'
        7'b0001000, // 'A'
        7'b0000011, // 'B'
        7'b1000110, // 'C'
        7'b0100001, // 'D'
        7'b0000110, // 'E'
        7'b0001110, // 'F'
        7'b1000010, // 'G'
        7'b0001001, // 'H'
        7'b1001111, // 'I'
        7'b1100001, // 'J'
        7'b0001010, // 'K'
        7'b1000111, // 'L'
        7'b0101010, // 'M'
        7'b0101011, // 'N'
        7'b0100011, // 'O'
        7'b0001100, // 'P'
        7'b0011000, // 'Q'
        7'b0101111, // 'R'
        7'b0010010, // 'S'
        7'b0000111, // 'T'
        7'b1000001, // 'U'
        7'b1100011, // 'V'
        7'b1100010, // 'W'
        7'b0011011, // 'X'
        7'b0010001, // 'Y'
        7'b0100100, // 'Z'
        7'b1111111, // '['
        7'b1111111, // '\'
        7'b1111111, // ']'
        7'b1111111, // '^'
        7'b1111111, // '_'
        7'b1111111, // '`'
        7'b0001000, // 'a'
        7'b0000011, // 'b'
        7'b1000110, // 'c'
        7'b0100001, // 'd'
        7'b0000110, // 'e'
        7'b0001110, // 'f'
        7'b1000010, // 'g'
        7'b0001001, // 'h'
        7'b1001111, // 'i'
        7'b1100001, // 'j'
        7'b0001010, // 'k'
        7'b1000111, // 'l'
        7'b0101010, // 'm'
        7'b0101011, // 'n'
        7'b0100011, // 'o'
        7'b0001100, // 'p'
        7'b0011000, // 'q'
        7'b0101111, // 'r'
        7'b0010010, // 's'
        7'b0000111, // 't'
        7'b1000001, // 'u'
        7'b1100011, // 'v'
        7'b1100010, // 'w'
        7'b0011011, // 'x'
        7'b0010001, // 'y'
        7'b0100100  // 'z'
    };

    logic [6:0] seg_encoded;

    assign seg_encoded =
        (char_captured >= 8'h30 && char_captured <= 8'h7A)
            ? SEG_LUT[char_captured - 8'h30]
            : 7'b0000110; // "E"rror

    `DFF(o_seg, seg_encoded, i_valid)

endmodule
